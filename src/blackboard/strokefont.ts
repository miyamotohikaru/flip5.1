/** 楕円の弧。deg は数学の角度（反時計回り、0° = 右） */
function arc(cx: number, cy: number, rx: number, ry: number, d0: number, d1: number, n = 14): number[] {
  const out: number[] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((d0 + (d1 - d0) * (i / n)) * Math.PI) / 180;
    out.push(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry);
  }
  return out;
}
