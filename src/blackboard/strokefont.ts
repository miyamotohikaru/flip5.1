export const FONT: Record<string, Glyph> = { ...DIGITS, ...UPPER, ...LOWER, ...SYM };

/** 無い字は '?' で代用（そこに何かが要ることは分かるように） */
export function glyphOf(ch: string): Glyph {
  return FONT[ch] ?? FONT["?"];
}
/** 字間（em）。黒板の手書きは字がばらけて置かれる。詰めすぎると「フォント」に見える */
export const TRACK = 0.034;
export function advanceOf(ch: string): number {
  return glyphOf(ch).adv + TRACK;
}

/** 字の上端・下端（em）。行の高さ・括弧の伸ばし方を決めるのに使う */
const BOUNDS = new Map<string, { y0: number; y1: number }>();
export function boundsOf(ch: string): { y0: number; y1: number } {
  const hit = BOUNDS.get(ch);
  if (hit) return hit;
  const g = glyphOf(ch);
  let y0 = 0, y1 = 0;
  for (const s of g.s) {
    for (let i = 1; i < s.length; i += 2) {
      if (s[i] < y0) y0 = s[i];
      if (s[i] > y1) y1 = s[i];
    }
  }
  const b = { y0, y1 };
  BOUNDS.set(ch, b);
  return b;
}
/** 文字列の幅（em） */
export function widthOf(text: string): number {
  let w = 0;
  for (const ch of text) w += advanceOf(ch);
  return w;
}

