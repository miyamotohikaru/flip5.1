// 手（ゆらぎ・反り・筆圧）

export type PenStroke = {
  /** SVG の d（M … L …） */
  d: string;
  /** 線の長さ（書き取りの dasharray に使う） */
  len: number;
  /** 太さの倍率（1 = 標準）。字の大きさに掛ける */
  w: number;
};

/** 決定的なゆらぎ。同じ (キー, 番号) なら必ず同じ値 [-0.5, 0.5] */
const j = (key: number, n: number) => hash2(key, n, 91) - 0.5;

/** 折れ線の長さ */
function polyLen(p: number[]): number {
  let L = 0;
  for (let i = 2; i < p.length; i += 2) L += Math.hypot(p[i] - p[i - 2], p[i + 1] - p[i - 1]);
  return L;
}

/** 長い辺を分割する（反りを乗せるため）。maxSeg は em 単位 */
function resample(p: number[], maxSeg: number): number[] {
  const out: number[] = [p[0], p[1]];
  for (let i = 2; i < p.length; i += 2) {
    const x0 = p[i - 2], y0 = p[i - 1], x1 = p[i], y1 = p[i + 1];
    const L = Math.hypot(x1 - x0, y1 - y0);
    const n = Math.max(1, Math.ceil(L / maxSeg));
    for (let k = 1; k <= n; k++) out.push(x0 + (x1 - x0) * (k / n), y0 + (y1 - y0) * (k / n));
  }
  return out;
}

const SLANT = 0.045; // 全体の傾き（右上がり）

/**
 * 1 文字を「人が書いた線」にする。
 * @param ch   文字
 * @param x    ベースライン左端（出力座標。y は下が正）
 * @param y    ベースライン
 * @param size em の大きさ（出力単位）
 * @param key  ゆらぎの種（位置から作る。同じ位置なら毎回同じ）
 */
export function handStrokes(ch: string, x: number, y: number, size: number, key: number): PenStroke[] {
  const g = glyphOf(ch);
  if (!g.s.length) return [];
  // 字ごとのばらつき
  const rot = j(key, 1) * 0.052;
  const sc = 1 + j(key, 2) * 0.055;
  const scy = 1 + j(key, 3) * 0.05;
  const ox = j(key, 4) * 0.028;
  const oy = j(key, 5) * 0.036;
  const slant = SLANT + j(key, 6) * 0.045;
  const cr = Math.cos(rot), sr = Math.sin(rot);
  const cx = g.adv * 0.5, cy = 0.32; // 回転の中心（字の重心あたり）

  const out: PenStroke[] = [];
  for (let si = 0; si < g.s.length; si++) {
    const raw = resample(g.s[si], 0.16);
    const n = raw.length / 2;
    // 反り: 弦に垂直な方向へ、中ほどが最大
    const ax = raw[0], ay = raw[1], bx = raw[raw.length - 2], by = raw[raw.length - 1];
    let nx = -(by - ay), ny = bx - ax;
    const nl = Math.hypot(nx, ny) || 1;
    nx /= nl;
    ny /= nl;
    const bow = j(key, 10 + si) * 0.055;
    const wob = j(key, 20 + si) * 0.022;
    const wobPh = hash2(key, 30 + si, 17) * 6.28;
    // 閉じた線（o, 0, O, θ, σ …）は弦が無いので、重心から外へふくらませる。
    // これをしないと円だけが完璧になり、「フォントを読み込んだ」ように見える
    const closed = Math.hypot(bx - ax, by - ay) < 0.14;
    let cx0 = 0, cy0 = 0;
    if (closed) {
      for (let i = 0; i < n; i++) {
        cx0 += raw[i * 2];
        cy0 += raw[i * 2 + 1];
      }
      cx0 /= n;
      cy0 /= n;
    }
    const rw1 = j(key, 50 + si) * 0.085;
    const rw2 = j(key, 60 + si) * 0.05;
    const rwPh = hash2(key, 70 + si, 41) * 6.28;
    let d = "";
    let len = 0;
    let px = 0, py = 0;
    for (let i = 0; i < n; i++) {
      const t = n > 1 ? i / (n - 1) : 0;
      let gx = raw[i * 2], gy = raw[i * 2 + 1];
      if (closed) {
        // 半径をゆらす（真円にしない）
        const dx = gx - cx0, dy = gy - cy0;
        const r = Math.hypot(dx, dy) || 1;
        const a = Math.atan2(dy, dx);
        const k = 1 + rw1 * Math.sin(a + rwPh) + rw2 * Math.sin(2 * a + rwPh * 1.7);
        gx = cx0 + dx * k;
        gy = cy0 + dy * k;
        void r;
      } else {
        // 反り＋ゆるいうねり
        const off = bow * Math.sin(Math.PI * t) + wob * Math.sin(Math.PI * 2.7 * t + wobPh);
        gx += nx * off;
        gy += ny * off;
      }
      // 傾き → 回転 → 拡大 → 位置
      gx += gy * slant;
      const rx = (gx - cx) * cr - (gy - cy) * sr + cx + ox;
      const ry = (gx - cx) * sr + (gy - cy) * cr + cy + oy;
      const sx = x + rx * sc * size;
      const sy = y - ry * scy * size; // y は下が正
      if (i === 0) d = `M${sx.toFixed(2)} ${sy.toFixed(2)}`;
      else {
        d += `L${sx.toFixed(2)} ${sy.toFixed(2)}`;
        len += Math.hypot(sx - px, sy - py);
      }
      px = sx;
      py = sy;
    }
    out.push({ d, len, w: 1 + j(key, 40 + si) * 0.22 });
  }
  return out;
}

/** 直線を1本、手で引く（打ち消し線・分数の横棒・√ の上棒）。少し反る */
export function handLine(x0: number, y0: number, x1: number, y1: number, key: number, bowScale = 1): PenStroke {
  const L = Math.hypot(x1 - x0, y1 - y0);
  const n = Math.max(2, Math.min(24, Math.round(L / 9)));
  let nx = -(y1 - y0) / (L || 1), ny = (x1 - x0) / (L || 1);
  const bow = j(key, 7) * 0.028 * L * bowScale;
  const wob = j(key, 8) * 0.012 * L * bowScale;
  const ph = hash2(key, 9, 23) * 6.28;
  let d = "";
  let len = 0, px = 0, py = 0;
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const off = bow * Math.sin(Math.PI * t) + wob * Math.sin(Math.PI * 3.3 * t + ph);
    const sx = x0 + (x1 - x0) * t + nx * off;
    const sy = y0 + (y1 - y0) * t + ny * off;
    if (i === 0) d = `M${sx.toFixed(2)} ${sy.toFixed(2)}`;
    else {
      d += `L${sx.toFixed(2)} ${sy.toFixed(2)}`;
      len += Math.hypot(sx - px, sy - py);
    }
    px = sx;
    py = sy;
  }
  return { d, len, w: 1 + j(key, 11) * 0.2 };
}

/**
 * 筆圧の「芯」。線の中ほど（15%〜85%）だけを取り出した d を返す。
 * これを太い線で重ねると、始点と終点が細くなる。
 */
export function coreOf(s: PenStroke): { d: string; len: number } | null {
  const pts = s.d
    .slice(1)
    .split("L")
    .map((p) => p.trim().split(/\s+/).map(Number));
  if (pts.length < 3) return null;
  const segs: number[] = [0];
  let total = 0;
  for (let i = 1; i < pts.length; i++) {
    total += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    segs.push(total);
  }
  if (total < 1e-3) return null;
  const a = total * 0.16, b = total * 0.84;
  const at = (dist: number): [number, number] => {
    for (let i = 1; i < segs.length; i++) {
      if (segs[i] >= dist) {
        const t = (dist - segs[i - 1]) / Math.max(segs[i] - segs[i - 1], 1e-6);
        return [pts[i - 1][0] + (pts[i][0] - pts[i - 1][0]) * t, pts[i - 1][1] + (pts[i][1] - pts[i - 1][1]) * t];
      }
    }
    return [pts[pts.length - 1][0], pts[pts.length - 1][1]];
  };
  const p0 = at(a);
  let d = `M${p0[0].toFixed(2)} ${p0[1].toFixed(2)}`;
  let len = 0;
  let px = p0[0], py = p0[1];
  for (let i = 1; i < pts.length; i++) {
    if (segs[i] <= a || segs[i] >= b) continue;
    d += `L${pts[i][0].toFixed(2)} ${pts[i][1].toFixed(2)}`;
    len += Math.hypot(pts[i][0] - px, pts[i][1] - py);
    px = pts[i][0];
    py = pts[i][1];
  }
  const p1 = at(b);
  d += `L${p1[0].toFixed(2)} ${p1[1].toFixed(2)}`;
  len += Math.hypot(p1[0] - px, p1[1] - py);
  return { d, len };
}
