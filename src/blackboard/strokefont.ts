/** 左右反転（] } ) ≥ などを作る） */
function mirror(s: number[][], w: number): number[][] {
  return s.map((p) => {
    const o = p.slice();
    for (let i = 0; i < o.length; i += 2) o[i] = w - o[i];
    return o;
  });
}
